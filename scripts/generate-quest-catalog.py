"""Compile official game quest text plus the legacy MIT catalog, entirely offline."""
import csv
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'third_party/mhworlddata/quests.csv'
rows = sorted(csv.DictReader(source.open(encoding='utf-8-sig', newline='')), key=lambda r: int(r['id']))
game_source = root / 'assets/quest_text/game_quests.csv'
game_rows = list(csv.DictReader(game_source.open(encoding='utf-8-sig', newline='')))
game_by_id = {int(row['id']): row for row in game_rows}
assert len(game_by_id) == len(game_rows)
legacy_by_id = {int(row['id']): row for row in rows}
by_text = {}
for row in game_rows:
    by_text.setdefault((row['name_en'], row['objective_en']), []).append(row)
columns=['en','es','pt','fr','de','it','ja','ko','zh-CN','zh-TW','ru','pl','ar','es-419']
def legacy_value(row,kind,language):
    # The original upstream zh is Traditional Chinese, not Simplified.
    mapped={'zh-TW':'zh','es-419':'es'}.get(language,language)
    return row.get(f'{kind}_{mapped}','')
def resolve(row,game,kind,language):
    value=game.get(f'{kind}_{language}','') or legacy_value(row,kind,language)
    if not value:value=game.get(f'{kind}_en','') or row.get(f'{kind}_en','')
    # Two Arabic titles select grammar by character gender in the game. The
    # static catalog uses the first official variant; never show literal tags.
    value=re.sub(r'<LSNR \{([^{}]*)\} \{[^{}]*\}>',r'\1',value)
    return value
compiled=[]
aliases=0
for identifier in sorted(set(legacy_by_id)|set(game_by_id)):
    row=legacy_by_id.get(identifier,{})
    game=game_by_id.get(identifier,{})
    if not game:
        candidates=by_text.get((row.get('name_en'),row.get('objective_en')),[])
        # Legacy databases sometimes assigned a different ID. Reuse localized
        # text only if exact English title+objective identify identical text.
        signatures={tuple(c.get(f'{kind}_{lang}','') for lang in columns for kind in ['name','objective']) for c in candidates}
        if len(signatures)==1:game=candidates[0];aliases+=1
    names=[resolve(row,game,'name',language) for language in columns]
    objectives=[resolve(row,game,'objective',language) for language in columns]
    assert all(names),identifier
    compiled.append((identifier,names,objectives))
ids = [row[0] for row in compiled]
assert len(set(ids)) == len(ids) and all(0 < i <= 1000000 for i in ids)
def literal(text):
    # Direction belongs to the renderer, not an unbalanced override embedded
    # in an upstream title (one Arabic entry contains U+202E).
    text=''.join(c for c in text if ord(c) not in {0x200e,0x200f,*range(0x202a,0x202f),*range(0x2066,0x206a)})
    assert all(ord(c) >= 32 for c in text)
    return 'L' + json.dumps(text, ensure_ascii=False)
lines = ['// Generated by scripts/generate-quest-catalog.py; see assets/quest_text/README.md.',
         '// Game text: CAPCOM. Legacy catalog: MHWorldData, Carlos Fernandez, MIT.',
         '#pragma once', '#include <array>', 'namespace meter {',
         'inline constexpr std::size_t QuestLocaleCount=14;',
         'struct QuestInfo { int id; std::array<const wchar_t*,QuestLocaleCount> names, objectives; };',
         'inline constexpr QuestInfo QuestCatalog[] = {']
for identifier,names,objectives in compiled:
    lines.append('    {'+str(identifier)+',{{'+','.join(map(literal,names))+'}},{{'+','.join(map(literal,objectives))+'}}},')
lines += ['};', '}']
(root / 'src/quest_catalog.hpp').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Generated {len(compiled)} quests for 14 game-text locales: {len(game_rows)} official IDs and {aliases} exact-text legacy aliases. Missing legacy translations retain English fallbacks.')
