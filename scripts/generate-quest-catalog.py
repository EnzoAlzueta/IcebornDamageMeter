"""Generate the multilingual quest index from the vendored MIT CSV (offline)."""
import csv
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'third_party/mhworlddata/quests.csv'
rows = sorted(csv.DictReader(source.open(encoding='utf-8-sig', newline='')), key=lambda r: int(r['id']))
ids = [int(r['id']) for r in rows]
assert len(set(ids)) == len(ids) and all(0 < i <= 1000000 for i in ids)
def literal(text):
    # Direction belongs to the renderer, not an unbalanced override embedded
    # in an upstream title (one Arabic entry contains U+202E).
    text=''.join(c for c in text if ord(c) not in {0x200e,0x200f,*range(0x202a,0x202f),*range(0x2066,0x206a)})
    assert all(ord(c) >= 32 for c in text)
    return 'L' + json.dumps(text, ensure_ascii=False)
lines = ['// Generated by scripts/generate-quest-catalog.py; see third_party/mhworlddata/README.md.',
         '// MHWorldData, Copyright (c) 2018 Carlos Fernandez, MIT license.',
         '#pragma once', '#include <array>', 'namespace meter {',
         'struct QuestInfo { int id; std::array<const wchar_t*,13> names, objectives; };',
         'inline constexpr QuestInfo QuestCatalog[] = {']
columns=['en','es','pt','fr','de','it','ja','ko',None,'zh','ru','pl','ar']
for row in rows:
    # Upstream zh is Traditional Chinese; unavailable translations use English.
    names=[(row.get('name_'+language,'') or row['name_en']) if language else row['name_en'] for language in columns]
    objectives=[(row.get('objective_'+language,'') or row['objective_en']) if language else row['objective_en'] for language in columns]
    lines.append('    {'+str(int(row['id']))+',{{'+','.join(map(literal,names))+'}},{{'+','.join(map(literal,objectives))+'}}},')
lines += ['};', '}']
(root / 'src/quest_catalog.hpp').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Generated {len(rows)} quests for 13 locales, with explicit English fallbacks.')
